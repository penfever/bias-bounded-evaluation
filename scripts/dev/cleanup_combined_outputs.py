#!/usr/bin/env python3
"""
Cleanup helper for Combined A-BB analyses and visualization artifacts.

Removes directories/files generated by:
  - scripts/analysis/run_combined_abb_analysis.py
  - scripts/visualization/run_all_visualizations.sh

Default targets include:
  * base_debiased_{strategy} directories for Combined A-BB outputs
  * tables_debiased_{strategy} directories (ELO bootstrap outputs)
  * tables/factor_scores_updated_cis (copied ranking CSVs)
  * combined A-BB comparison/summary figure folders under figures/
  * combined_abb_analysis_results.json summary file

Use --dry-run to preview removals.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path
from typing import Iterable, List, Set


BASE_DEBIASED_DIRS = [
    "base_debiased_combined_abb_conservative",
    "base_debiased_combined_abb_rms",
    "base_debiased_combined_abb_weighted",
    "base_debiased_abb_formatting_only",
]

TABLES_DEBIASED_DIRS = [
    "tables_debiased_conservative",
    "tables_debiased_rms",
    "tables_debiased_weighted",
    "tables_debiased_montecarlo",
    "tables_debiased_formatting_only",
]

TABLES_UPDATED_SUBPATH = Path("tables") / "factor_scores_updated_cis"

FIGURE_DIRS = [
    "combined_abb_comparisons",
    "combined_abb_visualizations",
    "individual_judges",
]

SUMMARY_FILENAME = "combined_abb_analysis_results.json"


def _resolve_default_paths() -> tuple[Path, Path]:
    script_path = Path(__file__).resolve()
    package_root = script_path.parents[2]
    repo_root = package_root.parent
    return package_root, repo_root


def _existing(paths: Iterable[Path]) -> List[Path]:
    return [p for p in paths if p.exists()]


def collect_data_targets(data_base: Path) -> List[Path]:
    if not data_base.exists():
        return []

    targets: List[Path] = []
    for judge_dir in sorted(p for p in data_base.iterdir() if p.is_dir()):
        if "-setting" not in judge_dir.name:
            continue

        # base_debiased_* directories
        for name in BASE_DEBIASED_DIRS:
            targets.append(judge_dir / name)

        # tables_debiased_* directories
        for name in TABLES_DEBIASED_DIRS:
            targets.append(judge_dir / name)

        # tables/factor_scores_updated_cis directory
        targets.append(judge_dir / TABLES_UPDATED_SUBPATH)

    # Combined summary JSON
    targets.append(data_base / SUMMARY_FILENAME)

    return _existing(targets)


def collect_figure_targets(figures_root: Path) -> List[Path]:
    if not figures_root.exists():
        return []

    targets: Set[Path] = set()
    for name in FIGURE_DIRS:
        targets.add(figures_root / name)

    # Legacy nested combined_abb_comparisons directories (e.g., tau_* / combined_abb_comparisons)
    for nested in figures_root.rglob("combined_abb_comparisons"):
        targets.add(nested)

    return _existing(sorted(targets))


def remove_path(path: Path, dry_run: bool) -> None:
    if dry_run:
        print(f"[dry-run] Would remove: {path}")
        return

    if path.is_dir():
        shutil.rmtree(path)
        print(f"Removed directory: {path}")
    else:
        path.unlink()
        print(f"Removed file: {path}")


def main() -> int:
    package_root, repo_root = _resolve_default_paths()

    parser = argparse.ArgumentParser(
        description="Remove Combined A-BB analysis and visualization artifacts."
    )
    parser.add_argument(
        "--data-base",
        type=Path,
        default=repo_root / "sos-addl-data" / "InDepthAnalysis",
        help="Path to Arena-Hard data base directory (default: auto-detected).",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=repo_root / "figures",
        help="Path to figures directory (default: auto-detected).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="List targets without deleting anything.",
    )

    args = parser.parse_args()

    data_base = args.data_base.expanduser().resolve()
    figures_dir = args.figures_dir.expanduser().resolve()

    print(f"Data base directory: {data_base}")
    print(f"Figures directory:   {figures_dir}")
    print(f"Dry run:             {args.dry_run}")
    print()

    targets: List[Path] = []
    targets.extend(collect_data_targets(data_base))

    figure_roots: Set[Path] = {figures_dir}
    package_figures = package_root / "figures"
    if package_figures != figures_dir:
        figure_roots.add(package_figures)

    for root in figure_roots:
        targets.extend(collect_figure_targets(root))

    if not targets:
        print("Nothing to clean.")
        return 0

    for path in sorted(set(targets)):
        remove_path(path, args.dry_run)

    if args.dry_run:
        print("\nDry run complete. No files were deleted.")
    else:
        print("\nCleanup complete.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
